/* * CH32H417 Fast Batch Flash (64KB Blocks)
 * address: Start address in Flash (0x08000000 base)
 * buffer: Pointer to host-side firmware data
 * count: Total bytes to write
 */
 #define KEY1 0x45670123
#define KEY2 0xCDEF89AB
int ch32h417_write_batch(struct flash_bank *bank, const uint8_t *buffer, 
                         uint32_t address, uint32_t count) {
    struct target *target = bank->target;
    struct working_area *stub_area, *source_area, *scratch_area;
    int retval = ERROR_OK;
    uint32_t ctlr;
    address |= 0x08000000;
    /* 1. Read Control Register to check LOCK status */
    retval = target_read_u32(target, 0x40022010, &ctlr);
    if (retval != ERROR_OK) return retval;

    /* If Bit 7 (LOCK) is set, we need to unlock */
    if (ctlr & (1 << 7)) {
        /* Unlock FLASH_CTLR */
        target_write_u32(target, 0x40022004, KEY1); // FLASH_KEYR
        target_write_u32(target, 0x40022004, KEY2);
        
        /* Unlock Fast Programming mode */
        target_write_u32(target, 0x40022024, KEY1); // FLASH_MODEKEYR
        target_write_u32(target, 0x40022024, KEY2);
    }
    // 1. Allocate Working Areas
    // Stub: The code blob (~512 bytes)
    // Source: Data window (128KB max per chunk)
    // Scratch: RMW Buffer (Fixed 64KB for DBMODE=1)
    target_alloc_working_area(target, sizeof(flash_algo_2_bin), &stub_area);
    target_alloc_working_area(target, 128 * 1024, &source_area);
    target_alloc_working_area(target, 64 * 1024, &scratch_area);

    // Load the binary stub once
    target_write_buffer(target, stub_area->address, sizeof(flash_algo_2_bin), flash_algo_2_bin);

    uint32_t bytes_remaining = count;
    uint32_t current_flash_addr = address;
    const uint8_t *host_ptr = buffer;

    while (bytes_remaining > 0) {
        uint32_t block_offset = (current_flash_addr - 0x08000000) % (64 * 1024);
        uint32_t chunk_size;

        /* Decide Chunk Size: 
           - Head: If unaligned, write until next 64K boundary
           - Middle: Max 128KB (aligned)
           - Tail: Remaining bytes (if < 64KB or unaligned)
        */
        if (block_offset != 0) {
            // Head: Unaligned start. Process only the first partial block.
            chunk_size = (64 * 1024) - block_offset;
            if (chunk_size > bytes_remaining) chunk_size = bytes_remaining;
        } else {
            // Aligned: Grab up to 128KB, but keep it 64KB block-aligned
            chunk_size = (bytes_remaining >= 128 * 1024) ? (128 * 1024) : bytes_remaining;
        }

        // Upload current chunk to target SRAM
        target_write_buffer(target, source_area->address, chunk_size, host_ptr);

        struct reg_param reg_params[5];
        init_reg_param(&reg_params[0], "a0", 32, PARAM_OUT); // reg_base
        buf_set_u32(reg_params[0].value, 0, 32, 0x40022000);

        init_reg_param(&reg_params[1], "a1", 32, PARAM_OUT); // flash_offset
        buf_set_u32(reg_params[1].value, 0, 32, current_flash_addr - 0x08000000);

        init_reg_param(&reg_params[2], "a2", 32, PARAM_OUT); // src_ptr
        buf_set_u32(reg_params[2].value, 0, 32, source_area->address);

        init_reg_param(&reg_params[3], "a3", 32, PARAM_OUT); // length
        buf_set_u32(reg_params[3].value, 0, 32, chunk_size);

        init_reg_param(&reg_params[4], "a4", 32, PARAM_OUT); // scratch_ptr
        buf_set_u32(reg_params[4].value, 0, 32, scratch_area->address);

        // Run the algorithm
        // Note: timeout is 10s for large 128K blocks (erasing/writing takes time)
        retval = target_run_algorithm(target, 0, NULL, 5, reg_params,
                                      stub_area->address, 0, 10000, NULL);

        for (int i = 0; i < 5; i++) destroy_reg_param(&reg_params[i]);

        if (retval != ERROR_OK) break;

        bytes_remaining -= chunk_size;
        current_flash_addr += chunk_size;
        host_ptr += chunk_size;
    }

    target_free_working_area(target, stub_area);
    target_free_working_area(target, source_area);
    target_free_working_area(target, scratch_area);

    return retval;
}
 
